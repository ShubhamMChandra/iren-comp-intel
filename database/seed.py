def seed_demo_signals(session=None) -> None:
    """Seed realistic demo signals for 15 diverse companies and generate score history.

    Idempotent: skips if the signals table already has rows.
    After seeding, every target company will have two ProspectScore rows
    (a lower baseline dated 14 days ago, then a freshly computed current score)
    so get_score_deltas() returns a positive delta for each — populating the
    Today page Call List immediately after first run.
    """
    from datetime import timedelta

    from database.db import get_session, init_db
    from database.models import ProspectScore, Signal
    from scoring.engine import score_all_prospects

    init_db()
    own_session = session is None
    if own_session:
        session = get_session()

    try:
        if session.query(Signal).count() > 0:
            print("Demo signals already present — skipping seed_demo_signals().")
            return

        now = datetime.now(timezone.utc)
        company_map = {c.name: c for c in session.query(Company).all()}

        # 1. Insert baseline (previous) ProspectScore rows dated 14 days ago
        #    with a lower total_score so the current rescore produces a positive delta.
        baseline_date = now - timedelta(days=14)
        baseline_count = 0
        for entry in SEED_SIGNALS:
            company = company_map.get(entry["company"])
            if not company:
                print(f"  [skip] {entry['company']} not found in DB — run seed_database() first.")
                continue
            session.add(
                ProspectScore(
                    company_id=company.id,
                    total_score=entry["baseline_score"],
                    scored_at=baseline_date,
                )
            )
            baseline_count += 1

        session.commit()
        print(f"Inserted {baseline_count} baseline ProspectScore rows (14 days ago).")

        # 2. Insert Signal rows for each company
        signal_count = 0
        for entry in SEED_SIGNALS:
            company = company_map.get(entry["company"])
            if not company:
                continue
            for s in entry["signals"]:
                detected_at = now - timedelta(days=s["days_ago"])
                session.add(
                    Signal(
                        company_id=company.id,
                        signal_type=s["type"],
                        title=s["title"],
                        summary=s.get("summary", ""),
                        source_type=s.get("source_type", "industry_news"),
                        magnitude=s.get("magnitude", 1.0),
                        is_active=True,
                        action_insight=s.get("action_insight"),
                        detected_at=detected_at,
                    )
                )
                signal_count += 1

        session.commit()
        print(f"Inserted {signal_count} demo signals across {len(SEED_SIGNALS)} companies.")

    finally:
        if own_session:
            session.close()

    # 3. Compute current scores — creates a new ProspectScore row per company
    #    dated "now", which will be higher than the 14-day-old baseline.
    print("Scoring all prospects to generate current score snapshot...")
    score_all_prospects()
    print("Demo signals seeded. Today page Call List should now show 10+ entries.")


def seed_database(use_web_search: bool = False, run_embed_after: bool = False):
    """Insert initial companies if database is empty.

    use_web_search: fetch company descriptions via DuckDuckGo and use them when available.
    run_embed_after: after committing, run local (Ollama) embedding backfill on signals.
    """
    init_db()
    session = get_session()

    existing = session.query(Company).count()
    if existing > 0:
        print(f"Database already has {existing} companies — skipping seed.")
        session.close()
        return

    if use_web_search:
        from database.seed_web import fetch_company_description
        print("Enriching company descriptions via web search...")

    count = 0
    for data in list(PROSPECTS):
        row = dict(data)
        if use_web_search:
            desc = fetch_company_description(row.get("name", ""), row.get("industry", ""))
            if desc:
                row["description"] = desc
        company = Company(company_type="prospect", **row)
        session.add(company)
        count += 1

    for data in list(COMPETITORS):
        row = dict(data)
        if use_web_search:
            desc = fetch_company_description(row.get("name", ""), row.get("industry", ""))
            if desc:
                row["description"] = desc
        company = Company(company_type="competitor", **row)
        session.add(company)
        count += 1

    session.flush()  # Ensure IDs are assigned before seeding contacts

    # Seed persona contacts
    company_map = {c.name: c for c in session.query(Company).all()}
    contact_count = 0
    for company_name, title, role_type, seniority, name, approach in CONTACTS:
        company = company_map.get(company_name)
        if company:
            contact = Contact(
                company_id=company.id,
                title=title,
                role_type=role_type,
                seniority=seniority,
                name=name,
                recommended_approach=approach,
            )
            session.add(contact)
            contact_count += 1

    session.commit()
    print(f"Seeded {count} companies ({len(PROSPECTS)} prospects, {len(COMPETITORS)} competitors).")
    print(f"Seeded {contact_count} persona contacts.")
    session.close()

    seed_demo_signals()

    if run_embed_after:
        from ai.embed_backfill import backfill_embeddings
        print("Running local embedding backfill (Ollama)...")
        backfill_embeddings(force=False)


def expand_prospects():
    """Add new prospects without touching existing companies or contacts."""
    init_db()
    session = get_session()

    existing_names = {c.name for c in session.query(Company).all()}
    count = 0
    for data in PROSPECTS:
        if data["name"] not in existing_names:
            company = Company(company_type="prospect", **data)
            session.add(company)
            count += 1

    session.commit()
    print(f"Added {count} new prospects ({len(existing_names)} already existed).")
    session.close()


